//! Test-tone adapter. It makes word-shaped beeps, not speech. It exists so the
//! pipeline, contract suite and CI never need a network or a speech engine.
//! Soundstage generates the audio itself, so its licence is commercial.

use crate::licence::Licence;
use crate::providers::*;
use crate::tags::Token;

pub struct ScratchAdapter;

const SR_OUT: u32 = 22_050;
const VERSION: &str = "scratch-tone-1";

struct Style {
    pitch: f32,
    amp: f32,
    pace: f32,
}

fn style_for(emotion: &str) -> Style {
    match emotion {
        "whisper" => Style { pitch: 1.0, amp: 0.15, pace: 0.95 },
        "shout" => Style { pitch: 1.15, amp: 0.9, pace: 1.1 },
        "excited" => Style { pitch: 1.2, amp: 0.6, pace: 1.15 },
        "sad" => Style { pitch: 0.9, amp: 0.4, pace: 0.85 },
        "tired" => Style { pitch: 0.85, amp: 0.35, pace: 0.75 },
        _ => Style { pitch: 1.0, amp: 0.5, pace: 1.0 },
    }
}

fn base_freq(voice_id: &str) -> Option<f32> {
    match voice_id {
        "tone:low" => Some(110.0),
        "tone:mid" => Some(180.0),
        "tone:high" => Some(260.0),
        _ => None,
    }
}

fn word(samples: &mut Vec<f32>, w: &str, freq: f32, st: &Style, pace: f32) {
    let jitter = 1.0 + (w.bytes().fold(0u32, |a, b| a.wrapping_mul(31).wrapping_add(b as u32)) % 21) as f32 / 100.0 - 0.1;
    let f0 = freq * st.pitch * jitter;
    let dur = (0.35 / (pace * st.pace)).max(0.05);
    let n = (dur * SR_OUT as f32) as usize;
    let edge = (0.015 * SR_OUT as f32) as usize;
    for i in 0..n {
        let t = i as f32 / SR_OUT as f32;
        let vib = 1.0 + 0.03 * (2.0 * std::f32::consts::PI * 5.0 * t).sin();
        let ph = 2.0 * std::f32::consts::PI * f0 * vib * t;
        let env = ((i.min(n - i) as f32) / edge as f32).min(1.0);
        samples.push(0.3 * st.amp * env * (ph.sin() + 0.3 * (2.0 * ph).sin()));
    }
    samples.extend(std::iter::repeat(0.0).take((0.04 * SR_OUT as f32) as usize));
}

impl Adapter for ScratchAdapter {
    fn id(&self) -> &'static str {
        "scratch-tone"
    }
    fn label(&self) -> &'static str {
        "Test tones (not speech)"
    }
    fn licence(&self) -> crate::licence::LicenceInfo {
        // Soundstage makes this audio itself, so there are no third-party terms that can go stale.
        licence_info(Licence::Commercial, "Generated by Soundstage itself", &crate::util::today_string(), "Synthetic tones with no third-party content.")
    }
    fn capabilities(&self) -> Capabilities {
        Capabilities {
            languages: vec!["zxx".into()],
            tags: ["whisper", "shout", "excited", "sad", "tired"].iter().map(|s| s.to_string()).collect(),
            voice_design: false,
            cloning: false,
            max_chars_per_request: 5000,
            streaming: false,
        }
    }
    fn list_voices(&self) -> Vec<Voice> {
        [("tone:low", "Low tone"), ("tone:mid", "Mid tone"), ("tone:high", "High tone")]
            .iter()
            .map(|(id, name)| Voice {
                id: id.to_string(),
                name: name.to_string(),
                provider: self.id().into(),
                language: "zxx".into(),
                accent: "None (tones only)".into(),
                gender: "n/a".into(),
                age_range: "n/a".into(),
                licence: self.licence(),
                sample_text: "One two three four.".into(),
                notes: "Beeps shaped like words. For checking timing and the mix, not for listening.".into(),
            })
            .collect()
    }
    fn provider_version(&self) -> String {
        VERSION.into()
    }
    fn render(&self, req: &RenderRequest) -> Result<RenderOutput, AdapterError> {
        precheck(&self.capabilities(), req)?;
        let freq = base_freq(&req.voice_id).ok_or_else(|| AdapterError::UnknownVoice(req.voice_id.clone()))?;
        let mut style = style_for(&req.emotion);
        let mut out = Vec::new();
        for t in &req.tokens {
            match t {
                Token::Text(s) => s.split_whitespace().for_each(|w| word(&mut out, w, freq, &style, req.pace)),
                Token::Delivery(d) => style = style_for(d),
                Token::Pause(ms) => out.extend(std::iter::repeat(0.0).take((*ms as usize * SR_OUT as usize) / 1000)),
                Token::NonVerbal(t) => return Err(AdapterError::UnsupportedTag(t.clone())),
            }
        }
        Ok(RenderOutput { samples: out, sample_rate: SR_OUT, provider_version: VERSION.into() })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn passes_the_adapter_contract() {
        let a = ScratchAdapter;
        let v = a.list_voices().remove(1);
        contract::run(&a, &v, "sneeze");
    }

    #[test]
    fn pauses_become_silence_of_the_right_length() {
        let a = ScratchAdapter;
        let req = |text: &str| RenderRequest { tokens: crate::tags::tokenize(text).0, voice_id: "tone:mid".into(), emotion: "neutral".into(), pace: 1.0, language: "zxx".into() };
        let base = a.render(&req("hello")).unwrap().samples.len();
        let paused = a.render(&req("hello [pause:500]")).unwrap().samples.len();
        assert_eq!(paused - base, SR_OUT as usize / 2);
    }

    #[test]
    fn unknown_voice_is_an_error() {
        let a = ScratchAdapter;
        let req = RenderRequest { tokens: crate::tags::tokenize("hi").0, voice_id: "tone:nope".into(), emotion: "neutral".into(), pace: 1.0, language: "zxx".into() };
        assert!(matches!(a.render(&req), Err(AdapterError::UnknownVoice(_))));
    }
}
