import { useEffect, useState } from "react";
import { api, messageOf } from "../api";
import { Confirm } from "../ui";

export function Settings(props: { info: { version: string; projects_root: string } | null; toast: (t: string, bad?: boolean) => void; onBack: () => void; inProject: boolean }) {
  const [has, setHas] = useState<boolean | null>(null);
  const [key, setKey] = useState("");
  const [removing, setRemoving] = useState(false);

  useEffect(() => { void api.hasApiKey("elevenlabs").then(setHas).catch(() => setHas(null)); }, []);

  const save = async () => {
    try { await api.setApiKey("elevenlabs", key); setKey(""); setHas(true); props.toast("Key saved to the Windows Credential Manager."); }
    catch (e) { props.toast(messageOf(e), true); }
  };

  return (
    <div className="page">
      <div className="row" style={{ marginBottom: 12 }}><h1 style={{ margin: 0 }}>Settings</h1><span className="spacer" /><button onClick={props.onBack}>{props.inProject ? "Back to project" : "Back"}</button></div>

      <div className="card">
        <h2>Voice providers</h2>
        <table><tbody>
          <tr><td><strong>Windows voices</strong><div className="small muted">Offline. Built into Windows.</div></td><td><span className="chip ok">✓ Ready, no key needed</span></td><td className="small muted">Licence unknown until you check the terms yourself.</td></tr>
          <tr><td><strong>Test tones</strong><div className="small muted">Beeps for checking timing.</div></td><td><span className="chip ok">✓ Ready</span></td><td className="small muted">Generated by Soundstage.</td></tr>
          <tr><td><strong>ElevenLabs</strong><div className="small muted">Cloud voices with expressive tags.</div></td><td><span className="chip warn">Not connected yet</span></td><td className="small muted">The adapter is not shipped in this version. You can store a key now; it is not used.</td></tr>
        </tbody></table>
        <h3 style={{ marginTop: 14 }}>ElevenLabs key</h3>
        <p className="small muted">Keys go to the Windows Credential Manager. They are never written to project files or logs, and the app never shows a saved key again.</p>
        <div className="row">
          <input type="password" autoComplete="off" aria-label="ElevenLabs key" value={key} maxLength={512} onChange={(e) => setKey(e.target.value)} placeholder={has ? "A key is saved" : "Paste a key"} style={{ minWidth: 320 }} />
          <button disabled={!key.trim()} onClick={() => void save()}>Save key</button>
          <button className="danger" disabled={!has} onClick={() => setRemoving(true)}>Remove saved key</button>
          <button disabled title="Available once the adapter ships">Test connection</button>
        </div>
      </div>

      <div className="card">
        <h2>Safety and licensing</h2>
        <ul>
          <li>Voice cloning is off in this version. It will require a verified consent record, and is refused without one.</li>
          <li>Commercial export is blocked for any voice, engine, music or effect whose licence is unknown, non-commercial, or not checked in the last 90 days.</li>
          <li>Scripts that look like fraud, impersonate public officials, or sexualise minors are not rendered.</li>
          <li>Every export carries a manifest that records the audio is AI-generated.</li>
        </ul>
      </div>

      <div className="card">
        <h2>About</h2>
        <p className="small">Soundstage {props.info?.version ?? ""}. Projects are stored in <span className="mono">{props.info?.projects_root ?? "…"}</span>. Deleting a project removes its folder.</p>
      </div>
      {removing && <Confirm title="Remove the saved ElevenLabs key?" confirmLabel="Remove key" onCancel={() => setRemoving(false)} body={<p>The key will be deleted from the Windows Credential Manager. You can save it again later.</p>}
        onConfirm={() => { void api.deleteApiKey("elevenlabs").then(() => { setHas(false); props.toast("Key removed."); }).catch((e) => props.toast(messageOf(e), true)); setRemoving(false); }} />}
    </div>
  );
}
